function MainWindow_CloseRequestFcn(hObject, ~, ~)
handles=gui.gethand;
batchModeActive=gui.retr('batchModeActive');
yes_synonyms = { ...
    'Absolutely', ...
    'Definitely', ...
    'Yes', ...
    'Of course', ...
    'Certainly', ...
    'Indeed', ...
    'Sure thing', ...
    'Right', ...
    'Yup', ...
    'Yep', ...
    'Yeah', ...
    'Aye', ...
    'You bet', ...
    'For sure', ...
    'Roger that', ...
    'Heck yeah', ...
    'Yes please', ...
    'Claro!', ...
    };
yes=yes_synonyms{randi(numel(yes_synonyms))};
no_synonyms = { ...
    'Nope', ...
    'No', ...
    'Nah', ...
    'No way', ...
    'Negative', ...
    'Never', ...
    'Not really', ...
    'Absolutely not', ...
    'By no means', ...
    'No, thank you', ...
    'Not today', ...
    'Probably not', ...
    'No thanks', ...
    'I think not', ...
    };
no=no_synonyms{randi(numel(no_synonyms))};

if batchModeActive == 0
    figure(hObject);drawnow
    button=gui.custom_msgbox('quest',getappdata(0,'hgui'),'Quit?','Do you want to quit PIVlab?','modal',{yes no},no);
else
    button = yes;
end
try
    gui.toolsavailable(1)
catch
end
if strcmp(button,yes)==1
    gui.end_of_session %preferences for the next start, hardware released (also used by "Reset PIVlab GUI")
    try
        delete(hObject);
    catch
        close(gcf,'force');
    end
end